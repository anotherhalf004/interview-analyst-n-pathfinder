import { GoogleGenAI } from "@google/genai";
import { z } from "zod";
import { zodToJsonSchema } from "zod-to-json-schema";
import temp from './temp.js';
import puppeteer from 'puppeteer';
import createDOMPurify from 'dompurify';
import { JSDOM } from 'jsdom';

const { resume, selfDescription, jobDescription } = temp;

// Initialize DOMPurify with JSDOM
const window = new JSDOM('').window;
const DOMPurify = createDOMPurify(window);

const ai = new GoogleGenAI({
    apiKey: process.env.GOOGLE_GENAI_API_KEY
});


const interviewReportSchema = z.object({
    matchScore: z.number().describe('The match score between the candidate and the job description'),
    technicalQuestions: z.array(z.object({
        question: z.string().describe('The technical questions can be asked in interview'),
        intention: z.string().describe('The intention of interview behind asking this question'),
        answer: z.string().describe('How to answer this question, what points to cover and what approach to take etc.')
    })).describe('Technical questions for software enginerr'),
    behavioralQuestions: z.array(z.object({
        question: z.string().describe('The technical questions can be asked in interview'),
        intention: z.string().describe('The intention of interview behind asking this question'),
        answer: z.string().describe('How to answer this question, what points to cover and what approach to take etc.')
    })).describe('Behavioural questions for software enginerr'),
    skillGaps: z.array(z.object({
        skill: z.string().describe('The skill gap between the candidate and the job description'),
        severity: z.enum(['high', 'medium', 'low']).describe('The severity of the skill gap'),
    })).describe('Skill gap between the candidate and the job description'),
    preparationPlan: z.array(z.object({
        day: z.number().describe('The day number in the preparation plan, starting from 1'),
        focus: z.string().describe('The main focus of day in prep plan'),
        tasks: z.array(z.string().describe('The list of tasks to be performed on the day'))
    })).describe('Preparation plan for the candidate'),
    title: z.string().describe('The title of the job for which interview report is generated'),

})

async function generateInterviewReport({ resume, selfDescription, jobDescription }) {

    const prompt = `Generate a interview report for a candidate based on the following information:
        Resume: ${resume}
        Self-Description: ${selfDescription}
        Job Description: ${jobDescription}
    `;


    const responseSchema = z.toJSONSchema(interviewReportSchema, {
        target: 'draft-07',
    });
    delete responseSchema.$schema;

    const response = await ai.models.generateContent({
        model: 'gemini-3.1-flash-lite',
        contents: prompt,
        config: {
            responseMimeType: 'application/json',
            responseSchema,
        }
    });

    const report = interviewReportSchema.parse(JSON.parse(response.text))
    return report;

}

async function generatePdfFromHtml(htmlContent) {
    const browser = await puppeteer.launch();
    const page = await browser.newPage();
    await page.setContent(htmlContent, { waitUntil: 'networkidle0' });

    const pdfBuffer = await page.pdf({ format: 'A4' });
    await browser.close();
    return pdfBuffer;
}

async function generateResumePdf({ resume, selfDescription, jobDescription }) {
    const resumepdfSchema = z.object({
        resume_html: z.string().describe('The HTML content of the resume'),
    })

    const prompt = `
    Generate a resume in HTML format for a candidate based on the following information:
    Resume: ${resume}
    Self-Description: ${selfDescription}
    Job Description: ${jobDescription}
    The resume should be tailored to the job description and highlight the candidate's relevant skills and experience.The HTML should be valid and well-formed and visually appealing.
    The content of resume should not sound like its generated by an AI and should be as close as possible to a human written resume.
    You can highlight content using some colors or different font style to make it more visually appealing.
    The content should be ATS friendly and be easily parsable by ATS systems.
    `;
    console.log(prompt);

    const response = await ai.models.generateContent({
        model: 'gemini-3.5-flash',
        contents: prompt,
        config: {
            responseMimeType: 'application/json',
            responseSchema: zodToJsonSchema(resumepdfSchema),
        }
    });

    const jsonContent = JSON.parse(response.text);
    // Sanitize HTML to prevent XSS
    const sanitizedHtml = DOMPurify.sanitize(jsonContent.resume_html, {
        ALLOWED_TAGS: ['html', 'head', 'body', 'style', 'h1', 'h2', 'h3', 'p', 'div', 'span', 'ul', 'li', 'strong', 'em', 'b', 'i', 'br', 'header', 'section'],
        ALLOWED_ATTR: ['class', 'id']
    });
    const pdfBuffer = await generatePdfFromHtml(sanitizedHtml);
    return pdfBuffer;

}

export default { generateInterviewReport, generateResumePdf };